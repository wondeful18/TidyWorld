#pragma once

#include <glm/mat4x4.hpp>
#include <glm/vec3.hpp>

namespace tinyworld {

//————————————————————————————————————————————————————————————————————————————————
// 相机围绕固定观察点转动，便于观察一栋房子的正面、侧面和背面。
//————————————————————————————————————————————————————————————————————————————————
struct OrbitCamera {
    glm::vec3 target{0.0f, 0.35f, 0.0f}; // 世界空间观察点，单位为米
    float azimuth{32.0f};                // 绕 Y 轴旋转角，单位为度
    float elevation{28.0f};              // 高于水平面的仰角，单位为度
    float distance{16.3f};               // 相机到观察点的距离，单位为米

    //————————————————————————————————————————————————————————————————————————————————
    // 返回根据球坐标求得的世界空间位置，单位为米。
    //————————————————————————————————————————————————————————————————————————————————
    [[nodiscard]] glm::vec3 Position() const;

    //————————————————————————————————————————————————————————————————————————————————
    // 返回相机的右手系视图矩阵。
    //————————————————————————————————————————————————————————————————————————————————
    [[nodiscard]] glm::mat4 View() const;

    //————————————————————————————————————————————————————————————————————————————————
    // 返回透视投影。zeroToOne 选择 WebGPU 深度区间，minimumFar 为远面最小米数。
    //————————————————————————————————————————————————————————————————————————————————
    [[nodiscard]] glm::mat4 Projection(float aspect, bool zeroToOne = true, float minimumFar = 80.0f) const;
};

}  // namespace tinyworld
