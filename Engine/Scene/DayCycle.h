#pragma once

#include "Engine/Scene/WorldScene.h"

namespace tinyworld {

//————————————————————————————————————————————————————————————————————————————————
// 供渲染各通道消费的一帧太阳和环境状态。未启用时间轴时取场景原值。
//————————————————————————————————————————————————————————————————————————————————
struct Daylight {
    DirectionalSun sun;
    float ambient{1.0f};   // 阴影区仍保留少量蓝调环境光
    float nightMix{};      // 天空、反射和天际线共用的夜景比例
};

//————————————————————————————————————————————————————————————————————————————————
// 将时刻约束到 [0, 24)，允许连续跨过午夜；输入单位为小时。
//————————————————————————————————————————————————————————————————————————————————
[[nodiscard]] float WrapDayHour(float hour);

//————————————————————————————————————————————————————————————————————————————————
// 将同一个周期高度换算为太阳方位、直射光和环境混合权重。
//————————————————————————————————————————————————————————————————————————————————
[[nodiscard]] Daylight EvaluateDaylight(float hour);

}  // namespace tinyworld
