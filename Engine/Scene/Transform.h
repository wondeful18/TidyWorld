#pragma once

#include <glm/mat4x4.hpp>
#include <glm/vec3.hpp>

namespace tinyworld {

//————————————————————————————————————————————————————————————————————————————————
// 可编辑物体的平移、旋转和缩放。本章约定右手系，Y 轴朝上。
//————————————————————————————————————————————————————————————————————————————————
struct Transform {
    glm::vec3 position{0.0f};         // 世界位置，单位为米
    glm::vec3 rotationDegrees{0.0f};  // 绕各轴的欧拉角，单位为度
    glm::vec3 scale{1.0f};            // 三轴正缩放比例

    //————————————————————————————————————————————————————————————————————————————————
    // 返回把局部顶点变到世界空间的 T × R × S 矩阵。
    //————————————————————————————————————————————————————————————————————————————————
    [[nodiscard]] glm::mat4 Matrix() const;
};

}  // namespace tinyworld
