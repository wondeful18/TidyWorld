#pragma once

#include "Engine/Scene/OrbitCamera.h"
#include "Engine/Scene/Transform.h"

namespace tinyworld {

//————————————————————————————————————————————————————————————————————————————————
// 漫游模式一帧的按键输入。正值分别代表前进和左转。
//————————————————————————————————————————————————————————————————————————————————
struct CarInput {
    float throttle{};  // 油门，范围为 [-1, 1]
    float steering{};  // 转向，范围为 [-1, 1]
    bool reset{};      // 请求回到出发点
};

//————————————————————————————————————————————————————————————————————————————————
// 在第 2 章的草地上更新车身变换和第三人称跟随相机。
//————————————————————————————————————————————————————————————————————————————————
class RoamingCar {
public:
    //————————————————————————————————————————————————————————————————————————————————
    // 把车身放到出发点并对准车后的镜头。此后由 Update 接管该变换。
    //————————————————————————————————————————————————————————————————————————————————
    explicit RoamingCar(Transform& body);

    //————————————————————————————————————————————————————————————————————————————————
    // 根据按键和本帧经过的秒数更新车身，然后让相机跟上。
    //————————————————————————————————————————————————————————————————————————————————
    void Update(Transform& body, CarInput input, float deltaSeconds);

    //————————————————————————————————————————————————————————————————————————————————
    // 借用当前跟随相机，供场景渲染使用。
    //————————————————————————————————————————————————————————————————————————————————
    [[nodiscard]] const OrbitCamera& Camera() const { return mCamera; }

private:
    //————————————————————————————————————————————————————————————————————————————————
    // 车头指向局部 +Z，从车后看向车身前方的观察点。
    //————————————————————————————————————————————————————————————————————————————————
    void Follow(const Transform& body);

    OrbitCamera mCamera;  // 漫游模式独立的相机，退出时保留原环绕视角
    float mSpeed{};      // 沿车头方向的有符号速度，单位为米每秒
};

}  // namespace tinyworld
