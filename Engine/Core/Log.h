#pragma once

#include <deque>
#include <mutex>
#include <string>
#include <string_view>

namespace tinyworld {

//————————————————————————————————————————————————————————————————————————————————
// 同时向终端和编辑器提供近期运行记录。
// WebGPU 可在其他线程报告错误，读写记录时使用同一把锁。
//————————————————————————————————————————————————————————————————————————————————
class Log {
public:
    //————————————————————————————————————————————————————————————————————————————————
    // 记录一条消息并写入终端。
    // level 用于区分普通信息、警告和错误。
    //————————————————————————————————————————————————————————————————————————————————
    void Write(std::string_view level, std::string_view message);

    //————————————————————————————————————————————————————————————————————————————————
    // 复制近期消息给编辑器渲染。
    // 调用方持有副本，绘制面板期间无需锁住日志。
    //————————————————————————————————————————————————————————————————————————————————
    [[nodiscard]] std::deque<std::string> Snapshot() const;

private:
    mutable std::mutex mMutex;       // 保护日志缓冲与终端输出
    std::deque<std::string> mLines;   // 最多保留 128 条近期消息
};

}  // namespace tinyworld
