#pragma once

#include "Engine/Platform/Window.h"
#include "Engine/Renderer/WgpuHandle.h"

#include <atomic>
#include <string>
#include <string_view>

namespace tinyworld {

class Log;

//————————————————————————————————————————————————————————————————————————————————
// 初始化并管理窗口对应的 WebGPU Device、Queue 和 Surface。
// 在主线程驱动请求与呈现，GPU 错误回调只记录诊断并置位。
//————————————————————————————————————————————————————————————————————————————————
class WebGpuContext {
public:
    //————————————————————————————————————————————————————————————————————————————————
    // 按 Surface、Adapter、Device、Queue 的依赖顺序启动 WebGPU。
    // window 与 log 由应用持有，生命周期覆盖上下文。
    //————————————————————————————————————————————————————————————————————————————————
    WebGpuContext(Window& window, Log& log);

    //————————————————————————————————————————————————————————————————————————————————
    // 解除 Surface 配置，随后按成员逆序释放引用。
    //————————————————————————————————————————————————————————————————————————————————
    ~WebGpuContext();

    //————————————————————————————————————————————————————————————————————————————————
    // 借用上下文的设备，用于创建本章绘制资源。
    //————————————————————————————————————————————————————————————————————————————————
    [[nodiscard]] WGPUDevice Device() const { return mDevice.get(); }

    //————————————————————————————————————————————————————————————————————————————————
    // 借用命令队列，用于上传顶点数据和提交每帧命令。
    //————————————————————————————————————————————————————————————————————————————————
    [[nodiscard]] WGPUQueue Queue() const { return mQueue.get(); }

    //————————————————————————————————————————————————————————————————————————————————
    // 返回已选定的 Surface 颜色格式。
    // Render Pipeline 和最终绘制目标须使用同一格式。
    //————————————————————————————————————————————————————————————————————————————————
    [[nodiscard]] WGPUTextureFormat SurfaceFormat() const { return mFormat; }

    //————————————————————————————————————————————————————————————————————————————————
    // 推进 WebGPU 事件并将设备错误带回应用主循环。
    //————————————————————————————————————————————————————————————————————————————————
    void ProcessEvents();

    //————————————————————————————————————————————————————————————————————————————————
    // 按当前 framebuffer 尺寸获取可绘制的 Surface 纹理。
    // 返回空句柄表示这帧应跳过呈现。
    //————————————————————————————————————————————————————————————————————————————————
    [[nodiscard]] TextureHandle AcquireFrame(PixelSize size);

    //————————————————————————————————————————————————————————————————————————————————
    // 呈现已经提交的窗口帧，检查底层返回状态。
    //————————————————————————————————————————————————————————————————————————————————
    void Present();

    //————————————————————————————————————————————————————————————————————————————————
    // 结束调用方已推入的 WebGPU 验证作用域。
    // 捕获验证失败时带上资源标签抛出错误。
    //————————————————————————————————————————————————————————————————————————————————
    void CheckValidation(std::string_view label);

    //————————————————————————————————————————————————————————————————————————————————
    // 有界地等待当前提交完成，用于退出前的验证。
    //————————————————————————————————————————————————————————————————————————————————
    void WaitForSubmittedWork();

private:
    //————————————————————————————————————————————————————————————————————————————————
    // 保存异步请求的结果与诊断。
    // 回调状态与上下文共存，覆盖取消和退出阶段。
    //————————————————————————————————————————————————————————————————————————————————
    struct RequestState {
        bool done{};         // 请求回调是否已经返回结果
        bool succeeded{};    // 回调是否报告成功
        std::string error;   // 从回调借用字符串复制的诊断

        //————————————————————————————————————————————————————————————————————————————————
        // 把请求结果存回主线程可读取的状态。
        // 即使复制错误消息失败，也不让异常越过回调边界。
        //————————————————————————————————————————————————————————————————————————————————
        void Complete(bool success, WGPUStringView message) noexcept;
    };

    //————————————————————————————————————————————————————————————————————————————————
    // 读取所选 Adapter 在当前 Surface 上公开的能力。
    // 初次选定颜色格式；重建时验证旧格式仍然可用。
    //————————————————————————————————————————————————————————————————————————————————
    void ReadSurfaceCapabilities();

    //————————————————————————————————————————————————————————————————————————————————
    // 将 Surface 配置为给定的非零 framebuffer 尺寸。
    //————————————————————————————————————————————————————————————————————————————————
    void Configure(PixelSize size);

    //————————————————————————————————————————————————————————————————————————————————
    // 在有限时间内等待 GPU 请求并检查回调结果。
    // 调用方提供的状态须比相应回调存活更久。
    //————————————————————————————————————————————————————————————————————————————————
    void WaitFor(const RequestState& state, std::string_view operation);

    //————————————————————————————————————————————————————————————————————————————————
    // 从 GPU 回调记录诊断，禁止异常越过 C API 回调边界。
    //————————————————————————————————————————————————————————————————————————————————
    void ReportGpuFailure(std::string_view category, WGPUStringView message) noexcept;

    Window& mWindow;                              // 借用窗口，供 Surface 重建
    Log& mLog;                                    // 借用线程安全的诊断日志
    std::atomic_bool mGpuFailed{false};            // 设备丢失或未捕获验证错误
    RequestState mAdapterState;                   // Adapter 请求的回调状态
    RequestState mDeviceState;                    // Device 请求的回调状态
    RequestState mValidationState;                // 当前验证作用域的回调状态
    RequestState mQueueState;                     // GPU 工作完成的回调状态
    InstanceHandle mInstance;                     // WebGPU 根引用
    SurfaceHandle mSurface;                       // 当前窗口的呈现目标引用
    AdapterHandle mAdapter;                       // 持有可呈现到该窗口的 Adapter
    DeviceHandle mDevice;                         // 用于创建和验证 GPU 资源
    QueueHandle mQueue;                           // 用于上传和命令提交
    WGPUTextureFormat mFormat{};                  // Surface 和 UI 输出约定的颜色格式
    PixelSize mConfiguredSize{};                   // 上次成功配置的 framebuffer 尺寸
    unsigned mRetryCount{};                       // 连续可恢复 Surface 失败次数
    bool mOccluded{};                             // 后端报告窗口暂时不可见时去重日志
};

}  // namespace tinyworld
