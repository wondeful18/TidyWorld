#pragma once

#include <cstdint>
#include <utility>

struct GLFWwindow;

namespace tinyworld {

//————————————————————————————————————————————————————————————————————————————————
// 表示实际可用于渲染的像素宽高。
// 尺寸为零时调用方应暂停对应的渲染通道。
//————————————————————————————————————————————————————————————————————————————————
struct PixelSize {
    std::uint32_t width{};   // 宽度，单位为像素
    std::uint32_t height{};  // 高度，单位为像素

    //————————————————————————————————————————————————————————————————————————————————
    // 按宽高比较尺寸，供纹理重建流程使用。
    //————————————————————————————————————————————————————————————————————————————————
    bool operator==(const PixelSize&) const = default;
};

//————————————————————————————————————————————————————————————————————————————————
// 持有第一章唯一的 GLFW 窗口。
// GLFW 初始化、事件处理和销毁均在主线程进行。
//————————————————————————————————————————————————————————————————————————————————
class Window {
public:
    //————————————————————————————————————————————————————————————————————————————————
    // 创建指定标题和逻辑大小的原生窗口。
    // 默认逻辑尺寸为 1280 × 720；visible 为 false 时仅供 GPU 回读。
    //————————————————————————————————————————————————————————————————————————————————
    explicit Window(const char* title, bool visible = true);

    //————————————————————————————————————————————————————————————————————————————————
    // 销毁窗口并结束本程序的 GLFW 会话。
    // 调用前须先释放依赖窗口的 WebGPU Surface。
    //————————————————————————————————————————————————————————————————————————————————
    ~Window();

    //————————————————————————————————————————————————————————————————————————————————
    // GLFW 会话具有唯一所有权，禁用复制构造。
    //————————————————————————————————————————————————————————————————————————————————
    Window(const Window&) = delete;

    //————————————————————————————————————————————————————————————————————————————————
    // 禁用复制赋值，防止同一个窗口句柄被销毁两次。
    //————————————————————————————————————————————————————————————————————————————————
    Window& operator=(const Window&) = delete;

    //————————————————————————————————————————————————————————————————————————————————
    // 借用 GLFW 句柄以创建 Surface 或接入 ImGui。
    // 返回值在窗口销毁前有效。
    //————————————————————————————————————————————————————————————————————————————————
    [[nodiscard]] GLFWwindow* Native() const;

    //————————————————————————————————————————————————————————————————————————————————
    // 查询用于 Surface 配置的 framebuffer 像素尺寸。
    // 最小化时向渲染循环报告零尺寸。
    //————————————————————————————————————————————————————————————————————————————————
    [[nodiscard]] PixelSize FramebufferPixels() const;

    //————————————————————————————————————————————————————————————————————————————————
    // 查询光标在 GLFW 窗口内的位置。
    // 返回的是窗口逻辑坐标，可直接用于统计面板。
    //————————————————————————————————————————————————————————————————————————————————
    [[nodiscard]] std::pair<double, double> CursorPosition() const;

private:
    GLFWwindow* mHandle{};  // 独占原生窗口，生命周期覆盖其 Surface
};

}  // namespace tinyworld
