#pragma once

#include "Editor/SceneViewport.h"

namespace tinyworld {

class Log;
class WebGpuContext;
class WorldEditor;

//————————————————————————————————————————————————————————————————————————————————
// 拥有单窗口 ImGui Docking 和两个官方后端。
// 场景目标留在 SceneViewport，UI 绘制写入窗口颜色视图。
//————————————————————————————————————————————————————————————————————————————————
class EditorUi {
public:
    //————————————————————————————————————————————————————————————————————————————————
    // 连接 GLFW 输入后端和 WebGPU 绘制后端。
    // 两个借用对象须在 EditorUi 销毁后再释放。
    //————————————————————————————————————————————————————————————————————————————————
    EditorUi(Window& window, WebGpuContext& gpu);

    //————————————————————————————————————————————————————————————————————————————————
    // 按后端先于 ImGui 上下文的顺序结束 UI。
    //————————————————————————————————————————————————————————————————————————————————
    ~EditorUi();

    //————————————————————————————————————————————————————————————————————————————————
    // ImGui 上下文在本章具有唯一所有权，禁用复制构造。
    //————————————————————————————————————————————————————————————————————————————————
    EditorUi(const EditorUi&) = delete;

    //————————————————————————————————————————————————————————————————————————————————
    // 禁用复制赋值，避免覆盖仍在使用的 UI 后端。
    //————————————————————————————————————————————————————————————————————————————————
    EditorUi& operator=(const EditorUi&) = delete;

    //————————————————————————————————————————————————————————————————————————————————
    // 生成 DockSpace、场景图片、日志与统计面板的绘制数据。
    // frameIntervalMs 是主循环两次采样之间的 CPU 墙钟时间。
    //————————————————————————————————————————————————————————————————————————————————
    void BuildFrame(const Log& log, PixelSize framebuffer, double frameIntervalMs, WorldEditor* world = nullptr);

    //————————————————————————————————————————————————————————————————————————————————
    // 把当前 ImGui 绘制数据编码进窗口颜色通道。
    // 调用时场景离屏通道已完成命令编码。
    //————————————————————————————————————————————————————————————————————————————————
    void Encode(WGPUCommandEncoder encoder, WGPUTextureView target) const;

    //————————————————————————————————————————————————————————————————————————————————
    // 借用本帧场景视口的纹理视图。
    //————————————————————————————————————————————————————————————————————————————————
    [[nodiscard]] WGPUTextureView SceneTarget() const { return mScene.ActiveTarget(); }

    //————————————————————————————————————————————————————————————————————————————————
    // 获取当前场景纹理像素尺寸，用于验证光栅目标变化。
    //————————————————————————————————————————————————————————————————————————————————
    [[nodiscard]] PixelSize SceneSize() const { return mScene.ActiveSize(); }

    //————————————————————————————————————————————————————————————————————————————————
    // 判断输入是否应交给编辑器之外的场景命令。
    //————————————————————————————————————————————————————————————————————————————————
    [[nodiscard]] bool AllowsSceneKeyboard() const;

private:
    Window& mWindow;        // 借用窗口以获取鼠标位置和 DPI 信息
    WGPUDevice mDevice;     // 借用与 ImGui 后端一致的 GPU 设备
    SceneViewport mScene;   // 持有当前场景显示资源
};

}  // namespace tinyworld
