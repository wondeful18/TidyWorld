#pragma once

#include "Engine/Platform/Window.h"
#include "Engine/Scene/WorldScene.h"

#include <optional>

namespace tinyworld {

//————————————————————————————————————————————————————————————————————————————————
// 将第二章的场景数据接入层级、属性面板和变换手柄。
// 选中状态和拖动状态归编辑器所有，渲染器只消费场景参数。
//————————————————————————————————————————————————————————————————————————————————
class WorldEditor {
public:
    //————————————————————————————————————————————————————————————————————————————————
    // 借用本章的场景数据以响应编辑操作。
    //————————————————————————————————————————————————————————————————————————————————
    explicit WorldEditor(WorldScene& scene) : mScene(scene) {}

    //————————————————————————————————————————————————————————————————————————————————
    // 显示三件物体、太阳以及可重复的场景演示。
    //————————————————————————————————————————————————————————————————————————————————
    void DrawHierarchy();

    //————————————————————————————————————————————————————————————————————————————————
    // 编辑选中物体的变换，或者调整太阳方位、仰角和强度。
    //————————————————————————————————————————————————————————————————————————————————
    void DrawInspector();

    //————————————————————————————————————————————————————————————————————————————————
    // 在图片上处理相机输入和 ImGuizmo。图片坐标用 ImGui 逻辑单位。
    //————————————————————————————————————————————————————————————————————————————————
    void DrawViewport(PixelSize size, float deltaSeconds);

private:
    //————————————————————————————————————————————————————————————————————————————————
    // 环绕、缩放并编辑物体。调用时当前 ImGui 项为场景图片。
    //————————————————————————————————————————————————————————————————————————————————
    void DrawEditControls(PixelSize size);

    //————————————————————————————————————————————————————————————————————————————————
    // 在视口拥有键盘焦点时读取驾驶按键，再推进本帧小车状态。
    //————————————————————————————————————————————————————————————————————————————————
    void UpdateDrive(float deltaSeconds);

    WorldScene& mScene;                        // 与渲染器共享的 CPU 场景
    std::optional<std::size_t> mSelected{2};   // 物体索引，空值表示选中太阳
    bool mRotate{};                           // 手柄切换为旋转模式
    bool mOrbiting{};                         // 鼠标右键已经从视口内开始拖动
};

}  // namespace tinyworld
